"""Benchmark workloads: deterministic request lists (seeded), identical for every backend.

Synthetic workloads send **token-id prompts** (``/v1/completions`` accepts a list of ints in vLLM,
native server and the HF baseline), so input lengths are exact and no backend's tokenizer or chat
template changes the work. ``ignore_eos`` fixes output lengths for the same reason. Token ids are
drawn from a range that avoids special tokens at the start of the vocabulary.

Chat workloads (multi-turn) use real OASST1 user turns and each backend's own chat template; their
outputs are generated by the backend under test and fed back into the conversation, so prefix reuse
covers generated tokens as in real use.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Literal

import numpy as np

from dli.bench.datasets import Conversation

TOKEN_LO = 1000  # below this, real vocabularies keep special and control tokens


def token_floor(vocab: int) -> int:
    """Lowest token id to sample: TOKEN_LO for real vocabularies, past 3 specials for test ones."""
    return TOKEN_LO if vocab >= 4 * TOKEN_LO else 3


@dataclass(frozen=True)
class LengthDist:
    """A token-length distribution: fixed, or log-normal with a median and clipping bounds."""

    kind: Literal["fixed", "lognormal"]
    value: int  # fixed length, or the median
    sigma: float = 0.0
    lo: int = 1
    hi: int = 1 << 30

    @staticmethod
    def fixed(n: int) -> LengthDist:
        return LengthDist("fixed", n, lo=n, hi=n)

    @staticmethod
    def lognormal(median: int, sigma: float, lo: int, hi: int) -> LengthDist:
        return LengthDist("lognormal", median, sigma, lo, hi)

    def sample(self, rng: np.random.Generator, n: int) -> list[int]:
        if self.kind == "fixed":
            return [self.value] * n
        x = rng.lognormal(np.log(self.value), self.sigma, size=n)
        return [int(v) for v in np.clip(np.rint(x), self.lo, self.hi)]

    def describe(self) -> dict[str, Any]:
        return {
            "kind": self.kind,
            "value": self.value,
            "sigma": self.sigma,
            "lo": self.lo,
            "hi": self.hi,
        }


@dataclass(frozen=True)
class GenRequest:
    """One completion request. Exactly one of ``prompt`` (token ids) or ``messages`` is set."""

    rid: str
    max_tokens: int
    prompt: tuple[int, ...] | None = None
    messages: tuple[tuple[str, str], ...] | None = None
    priority: str | None = None

    @property
    def prompt_len(self) -> int | None:
        return len(self.prompt) if self.prompt is not None else None


@dataclass(frozen=True)
class Session:
    """A multi-turn conversation: turns are issued one after another by the load generator."""

    sid: str
    system: str
    user_turns: tuple[str, ...]
    max_tokens: int


@dataclass(frozen=True)
class Workload:
    name: str
    requests: tuple[GenRequest, ...] = ()
    sessions: tuple[Session, ...] = ()
    params: dict[str, Any] = field(default_factory=dict)

    @property
    def is_sessions(self) -> bool:
        return bool(self.sessions)


def _tokens(rng: np.random.Generator, n: int, vocab: int) -> tuple[int, ...]:
    return tuple(int(t) for t in rng.integers(token_floor(vocab), vocab, size=n))


def synthetic(
    name: str,
    n: int,
    input_len: LengthDist,
    output_len: LengthDist,
    *,
    vocab: int,
    seed: int = 0,
) -> Workload:
    """Independent random-token prompts: no prefix sharing, exact lengths."""
    rng = np.random.default_rng(seed)
    ins, outs = input_len.sample(rng, n), output_len.sample(rng, n)
    reqs = tuple(
        GenRequest(f"{name}-{i}", outs[i], prompt=_tokens(rng, ins[i], vocab)) for i in range(n)
    )
    params = {
        "n": n,
        "input_len": input_len.describe(),
        "output_len": output_len.describe(),
        "vocab": vocab,
        "seed": seed,
    }
    return Workload(name, reqs, params=params)


def shared_prefix(
    name: str,
    n: int,
    *,
    num_prefixes: int,
    prefix_len: int,
    suffix_len: LengthDist,
    output_len: LengthDist,
    zipf_s: float,
    vocab: int,
    seed: int = 0,
) -> Workload:
    """Each prompt = one of ``num_prefixes`` shared prefixes (Zipf popularity) + a unique suffix.

    Models a fleet of applications, each with its own long system prompt or few-shot preamble.
    """
    rng = np.random.default_rng(seed)
    prefixes = [_tokens(rng, prefix_len, vocab) for _ in range(num_prefixes)]
    weights = 1.0 / np.arange(1, num_prefixes + 1) ** zipf_s
    choice = rng.choice(num_prefixes, size=n, p=weights / weights.sum())
    sufs, outs = suffix_len.sample(rng, n), output_len.sample(rng, n)
    reqs = tuple(
        GenRequest(
            f"{name}-{i}", outs[i], prompt=prefixes[int(choice[i])] + _tokens(rng, sufs[i], vocab)
        )
        for i in range(n)
    )
    params = {
        "n": n,
        "num_prefixes": num_prefixes,
        "prefix_len": prefix_len,
        "suffix_len": suffix_len.describe(),
        "output_len": output_len.describe(),
        "zipf_s": zipf_s,
        "vocab": vocab,
        "seed": seed,
    }
    return Workload(name, reqs, params=params)


def multi_turn(
    name: str,
    conversations: Sequence[Conversation],
    *,
    num_sessions: int,
    system_prompts: Sequence[str],
    max_turns: int,
    output_tokens: int,
    seed: int = 0,
) -> Workload:
    """Sessions from real OASST1 conversations, each with one of a few shared system prompts."""
    if num_sessions > len(conversations):
        raise ValueError(
            f"only {len(conversations)} conversations available, {num_sessions} requested"
        )
    rng = np.random.default_rng(seed)
    picks = rng.permutation(len(conversations))[:num_sessions]
    sessions = tuple(
        Session(
            f"{name}-s{i}",
            system_prompts[int(rng.integers(0, len(system_prompts)))],
            conversations[int(c)].user_turns[:max_turns],
            output_tokens,
        )
        for i, c in enumerate(picks)
    )
    params = {
        "num_sessions": num_sessions,
        "max_turns": max_turns,
        "output_tokens": output_tokens,
        "num_system_prompts": len(system_prompts),
        "seed": seed,
        "turns_total": sum(len(s.user_turns) for s in sessions),
    }
    return Workload(name, sessions=sessions, params=params)


def load_system_prompts(path: Path) -> list[str]:
    prompts: list[str] = json.loads(path.read_text())
    return prompts
